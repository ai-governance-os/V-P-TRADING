const fs=require('node:fs'),assert=require('node:assert/strict'),{JSDOM}=require('jsdom');
async function main(){
  const dom=new JSDOM(fs.readFileSync('gas/Index.html','utf8'),{runScripts:'dangerously',url:'https://test.local'});
  const w=dom.window,d=w.document;
  w.S.user={name:'TEST',role:'admin'};w.S.boot={};w.S.view='order';
  ['renderOrder','loadList','loadDriver','loadDash','loadBill','loadSettings'].forEach(fn=>w[fn]=()=>{});
  let confirms=0,consent=true;w.confirm=()=>{confirms++;return consent};
  const tick=()=>new Promise(r=>w.setTimeout(r,30));
  const move=async direction=>{w.history[direction]();await tick()};
  w.renderApp();const initial=w.history.length;
  assert.ok(d.getElementById('appBack').disabled,'root button is disabled');
  w.go('driver');assert.equal(w.S.view,'driver');assert.ok(!d.getElementById('appBack').disabled);
  w.go('driver');assert.equal(w.history.length,initial+1,'repeated active-tab taps do not add history');
  w.go('dash');await move('back');assert.equal(w.S.view,'driver','hardware Back returns to delivery');
  await move('back');assert.equal(w.S.view,'order','second Back returns home without logging out');
  assert.ok(w.S.user);
  await move('forward');assert.equal(w.S.view,'driver','Forward restores valid route');
  w.go('set');w.appBack_();await tick();assert.equal(w.S.view,'driver','visible Back uses same history');
  const beforeSheet=w.history.length;
  w.openSheet('<input id="edit" value="ORIGINAL"><button onclick="closeSheet()">取消</button>');
  w.openSheet('<input id="edit" value="ORIGINAL"><button onclick="closeSheet()">取消</button>');
  assert.equal(w.SHEETNAV,1,'redrawing a sheet adds only one history entry');
  await move('back');assert.equal(w.S.view,'driver');assert.ok(!d.getElementById('sheet').classList.contains('on'));
  assert.equal(confirms,0,'unchanged prefilled input closes without a warning');
  w.openSheet('<input id="edit" value="ORIGINAL">');
  d.getElementById('edit').value='DRAFT';d.getElementById('edit').dispatchEvent(new w.Event('input',{bubbles:true}));
  consent=false;await move('back');assert.equal(d.getElementById('edit').value,'DRAFT');
  assert.ok(d.getElementById('sheet').classList.contains('on'),'declining discard keeps sheet and history');
  consent=true;await move('back');assert.ok(!d.getElementById('sheet').classList.contains('on'));assert.equal(w.S.view,'driver');
  w.openSheet('<input id="edit">');d.getElementById('edit').dispatchEvent(new w.Event('input',{bubbles:true}));
  const beforeCancel=confirms;w.closeSheet();await tick();assert.equal(confirms,beforeCancel,'explicit Cancel is not confirmed twice');
  await move('back');assert.equal(w.S.view,'order','closing sheets does not strand an extra blank navigation step');
  await move('back');assert.ok(w.S.user);assert.match(d.getElementById('toast').textContent,/已在首页/,'root boundary explains next Back exits');
  w.go('set');const token=w.NAV_SESSION;w.logout();
  assert.equal(w.NAV_SESSION,'');assert.ok(!w.S.user);
  await move('back');assert.ok(!w.S.user);assert.ok(!d.getElementById('v-set'),'old history cannot restore logged-out account');
  w.S.user={name:'DRIVER',role:'driver'};w.S.boot={};w.S.view='driver';w.renderApp();
  assert.notEqual(w.NAV_SESSION,token);w.go('set');assert.equal(w.S.view,'driver','route history respects role');
  w.go('bill');await move('back');assert.equal(w.S.view,'driver','driver returns from statement to delivery');
  w.openSheet('<textarea data-sheet-clean>NOTIFICATION</textarea>');
  d.querySelector('textarea').dispatchEvent(new w.Event('input',{bubbles:true}));assert.equal(w.SHEET_EDITED,false,'copy-only notification text is not an edit');
  await move('back');assert.equal(w.S.view,'driver');
  dom.window.close();console.log('Back/Forward, root boundary, modal edits/cancel, logout and role navigation checks passed');
}
main().catch(e=>{console.error(e);process.exit(1)});
